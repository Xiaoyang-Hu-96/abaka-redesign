// Builds design tokens from tokens/tokens.json (W3C DTCG format).
//
// Output 1: app/tokens.css  – a Tailwind v4 `@theme` block. Tailwind turns each
//           variable into a CSS custom property AND a utility class, so
//           `color.text.primary` becomes `var(--color-text-primary)` and `text-text-primary`.
// Output 2: lib/tokens.ts   – the same values for JavaScript (the hero canvas draws with them).
import StyleDictionary from "style-dictionary";

const sd = new StyleDictionary({
  source: ["tokens/tokens.json"],
  usesDtcg: true,
  platforms: {
    css: {
      // Keep values exactly as authored (px, hex), only kebab-case the names.
      transforms: ["name/kebab"],
      buildPath: "app/",
      files: [
        {
          destination: "tokens.css",
          format: "css/variables",
          options: {
            selector: "@theme",
            outputReferences: true,
            fileHeader: () => ["Generated by scripts/build-tokens.mjs. Do not edit; edit tokens/tokens.json."],
          },
        },
      ],
    },
    js: {
      transforms: ["name/camel"],
      buildPath: "lib/",
      files: [
        {
          destination: "tokens.ts",
          format: "javascript/es6",
          options: {
            fileHeader: () => ["Generated by scripts/build-tokens.mjs. Do not edit; edit tokens/tokens.json."],
          },
        },
      ],
    },
  },
});

await sd.buildAllPlatforms();
